--5. Calculate month-over-month growth percentage.
SELECT
    MONTH,
    Month_Number,
    Monthly_Sales,
    Previous_Month_Sales,
    ROUND(
        ((Monthly_Sales - Previous_Month_Sales)
        / Previous_Month_Sales) * 100,
        2
    ) AS MoM_Growth_Percentage
FROM (
    SELECT
        MONTH,
        Month_Number,
        Monthly_Sales,
        LAG(Monthly_Sales) OVER (
            ORDER BY Month_Number
        ) AS Previous_Month_Sales
    FROM (
        SELECT
            TO_CHAR(o.Order_Date, 'Month') AS MONTH,
            EXTRACT(MONTH FROM o.Order_Date) AS Month_Number,
            SUM(
                od.Quantity * p.Selling_Price * (1 - od.Discount / 100)
            ) AS Monthly_Sales
        FROM Orders o
        JOIN Order_Details od
            ON o.Order_ID = od.Order_ID
        JOIN Products p
            ON od.Product_ID = p.Product_ID
        GROUP BY
            EXTRACT(MONTH FROM o.Order_Date),
            TO_CHAR(o.Order_Date, 'Month')
    ) AS Monthly_Sales_Data
) AS Monthly_Comparison
ORDER BY Month_Number;

