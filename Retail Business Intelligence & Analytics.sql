--A SQL View named Branch_Expansion_Report

CREATE OR REPLACE VIEW Branch_Expansion_Report AS

WITH Branch_Sales AS (
    SELECT
        b.Branch_ID,
        b.Branch_Name,
        b.City,
        b.Region,

        SUM(
            od.Quantity * p.Selling_Price
            * (1 - od.Discount / 100)
        ) AS Total_Revenue,

        SUM(
            od.Quantity *
            (
                p.Selling_Price * (1 - od.Discount / 100)
                - p.Cost_Price
            )
        ) AS Total_Profit,

        COUNT(DISTINCT o.Order_ID) AS Total_Orders,

        COUNT(DISTINCT o.Customer_ID) AS Total_Customers

    FROM Branches b
    JOIN Employees e
        ON b.Branch_ID = e.Branch_ID
    JOIN Orders o
        ON e.Employee_ID = o.Employee_ID
    JOIN Order_Details od
        ON o.Order_ID = od.Order_ID
    JOIN Products p
        ON od.Product_ID = p.Product_ID

    GROUP BY
        b.Branch_ID,
        b.Branch_Name,
        b.City,
        b.Region
),

Branch_Profit_Percentage AS (
    SELECT
        Branch_ID,
        ROUND(
            Total_Profit / NULLIF(Total_Revenue, 0) * 100,
            2
        ) AS Profit_Percentage
    FROM Branch_Sales
),

Branch_Average_Order_Value AS (
    SELECT
        Branch_ID,
        ROUND(
            Total_Revenue / NULLIF(Total_Orders, 0),
            2
        ) AS Average_Order_Value
    FROM Branch_Sales
),

Branch_Ranks AS (
    SELECT
        Branch_ID,

        RANK() OVER (
            ORDER BY Total_Revenue DESC
        ) AS Branch_Revenue_Rank,

        RANK() OVER (
            ORDER BY Total_Profit DESC
        ) AS Branch_Profit_Rank

    FROM Branch_Sales
),

Employee_Sales AS (
    SELECT
        e.Branch_ID,
        e.Employee_ID,
        e.Employee_Name,

        SUM(
            od.Quantity * p.Selling_Price
            * (1 - od.Discount / 100)
        ) AS Total_Sales

    FROM Employees e
    JOIN Orders o
        ON e.Employee_ID = o.Employee_ID
    JOIN Order_Details od
        ON o.Order_ID = od.Order_ID
    JOIN Products p
        ON od.Product_ID = p.Product_ID

    GROUP BY
        e.Branch_ID,
        e.Employee_ID,
        e.Employee_Name
),

Top_Employees AS (
    SELECT
        Branch_ID,
        Employee_Name AS Top_Employee
    FROM (
        SELECT
            Branch_ID,
            Employee_Name,
            Total_Sales,
            RANK() OVER (
                PARTITION BY Branch_ID
                ORDER BY Total_Sales DESC
            ) AS Employee_Rank
        FROM Employee_Sales
    ) x
    WHERE Employee_Rank = 1
),

Product_Sales AS (
    SELECT
        e.Branch_ID,
        p.Product_ID,
        p.Product_Name,

        SUM(
            od.Quantity * p.Selling_Price
            * (1 - od.Discount / 100)
        ) AS Total_Product_Revenue

    FROM Employees e
    JOIN Orders o
        ON e.Employee_ID = o.Employee_ID
    JOIN Order_Details od
        ON o.Order_ID = od.Order_ID
    JOIN Products p
        ON od.Product_ID = p.Product_ID

    GROUP BY
        e.Branch_ID,
        p.Product_ID,
        p.Product_Name
),

Top_Products AS (
    SELECT
        Branch_ID,
        Product_Name AS Top_Product
    FROM (
        SELECT
            Branch_ID,
            Product_Name,
            Total_Product_Revenue,
            RANK() OVER (
                PARTITION BY Branch_ID
                ORDER BY Total_Product_Revenue DESC
            ) AS Product_Rank
        FROM Product_Sales
    ) x
    WHERE Product_Rank = 1
),

Category_Sales AS (
    SELECT
        e.Branch_ID,
        p.Category,

        SUM(
            od.Quantity * p.Selling_Price
            * (1 - od.Discount / 100)
        ) AS Category_Revenue

    FROM Employees e
    JOIN Orders o
        ON e.Employee_ID = o.Employee_ID
    JOIN Order_Details od
        ON o.Order_ID = od.Order_ID
    JOIN Products p
        ON od.Product_ID = p.Product_ID

    GROUP BY
        e.Branch_ID,
        p.Category
),

Best_Categories AS (
    SELECT
        Branch_ID,
        Category AS Best_Category
    FROM (
        SELECT
            Branch_ID,
            Category,
            Category_Revenue,
            RANK() OVER (
                PARTITION BY Branch_ID
                ORDER BY Category_Revenue DESC
            ) AS Category_Rank
        FROM Category_Sales
    ) x
    WHERE Category_Rank = 1
),

Customer_Order_Counts AS (
    SELECT
        e.Branch_ID,
        o.Customer_ID,
        COUNT(DISTINCT o.Order_ID) AS Order_Count

    FROM Employees e
    JOIN Orders o
        ON e.Employee_ID = o.Employee_ID

    GROUP BY
        e.Branch_ID,
        o.Customer_ID
),

Repeat_Customer_Percentage AS (
    SELECT
        Branch_ID,
        ROUND(
            COUNT(
                CASE
                    WHEN Order_Count > 1 THEN 1
                END
            ) * 100.0
            / NULLIF(COUNT(*), 0),
            2
        ) AS Repeat_Customer_Percentage

    FROM Customer_Order_Counts

    GROUP BY Branch_ID
),

Inventory_Values AS (
    SELECT
        i.Branch_ID,

        SUM(
            i.Stock_Quantity * p.Cost_Price
        ) AS Total_Inventory_Value

    FROM Inventory i
    JOIN Products p
        ON i.Product_ID = p.Product_ID

    GROUP BY i.Branch_ID
)

SELECT
    bs.Branch_Name,
    bs.City,
    bs.Region,

    ROUND(bs.Total_Revenue, 2) AS Total_Revenue,
    ROUND(bs.Total_Profit, 2) AS Total_Profit,

    bpp.Profit_Percentage,

    bs.Total_Orders,
    bs.Total_Customers,

    bao.Average_Order_Value,

    te.Top_Employee,
    tp.Top_Product,
    bc.Best_Category,

    rcp.Repeat_Customer_Percentage,

    ROUND(iv.Total_Inventory_Value, 2)
        AS Total_Inventory_Value,

    br.Branch_Revenue_Rank,
    br.Branch_Profit_Rank

FROM Branch_Sales bs

LEFT JOIN Branch_Profit_Percentage bpp
    ON bs.Branch_ID = bpp.Branch_ID

LEFT JOIN Branch_Average_Order_Value bao
    ON bs.Branch_ID = bao.Branch_ID

LEFT JOIN Branch_Ranks br
    ON bs.Branch_ID = br.Branch_ID

LEFT JOIN Top_Employees te
    ON bs.Branch_ID = te.Branch_ID

LEFT JOIN Top_Products tp
    ON bs.Branch_ID = tp.Branch_ID

LEFT JOIN Best_Categories bc
    ON bs.Branch_ID = bc.Branch_ID

LEFT JOIN Repeat_Customer_Percentage rcp
    ON bs.Branch_ID = rcp.Branch_ID

LEFT JOIN Inventory_Values iv
    ON bs.Branch_ID = iv.Branch_ID

ORDER BY
    br.Branch_Revenue_Rank;
    
SELECT * FROM branch_expansion_report;